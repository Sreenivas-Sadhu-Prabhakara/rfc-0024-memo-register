package main

import (
	"fmt"
	"html/template"
	"strings"
)

type Socket struct {
	User uint32 `json:"user"`
	Host uint32 `json:"host"`
	AEN  uint32 `json:"aen"`
}
type Case struct {
	Name       string  `json:"name"`
	Local      Socket  `json:"local"`
	Remote     Socket  `json:"remote"`
	RelabelAEN *uint32 `json:"relabel_aen,omitempty"`
}
type Scenario struct {
	Cases []Case `json:"cases"`
}
type View struct {
	Socket
	Hex       string `json:"hex"`
	Direction string `json:"direction"`
}
type Relabel struct {
	Proposed View `json:"proposed"`
	Allowed  bool `json:"allowed"`
}
type Result struct {
	Name               string   `json:"name"`
	Local              View     `json:"local"`
	Remote             View     `json:"remote"`
	OppositeDirections bool     `json:"opposite_directions"`
	Relabel            *Relabel `json:"relabel,omitempty"`
}
type Report struct {
	Cases []Result `json:"cases"`
}

func view(s Socket) (View, error) {
	if s.User > 0xffffff || s.Host > 255 || s.AEN > 255 {
		return View{}, fmt.Errorf("socket exceeds 24/8/8-bit widths")
	}
	dir := "receive"
	if s.AEN&1 == 1 {
		dir = "send"
	}
	return View{s, fmt.Sprintf("%06x%02x%02x", s.User, s.Host, s.AEN), dir}, nil
}
func plan(s Scenario) (Report, error) {
	r := Report{}
	if len(s.Cases) == 0 || len(s.Cases) > 100 {
		return r, fmt.Errorf("expected 1–100 cases")
	}
	seen := map[string]bool{}
	for _, c := range s.Cases {
		if strings.TrimSpace(c.Name) == "" || len(c.Name) > 100 || seen[c.Name] {
			return Report{}, fmt.Errorf("names must be nonblank, unique, and at most 100 bytes")
		}
		seen[c.Name] = true
		l, e := view(c.Local)
		if e != nil {
			return Report{}, e
		}
		remote, e := view(c.Remote)
		if e != nil {
			return Report{}, e
		}
		row := Result{Name: c.Name, Local: l, Remote: remote, OppositeDirections: c.Local.AEN&1 != c.Remote.AEN&1}
		if c.RelabelAEN != nil {
			p := c.Local
			p.AEN = *c.RelabelAEN
			v, e := view(p)
			if e != nil {
				return Report{}, e
			}
			row.Relabel = &Relabel{v, p.AEN&1 == c.Local.AEN&1}
		}
		r.Cases = append(r.Cases, row)
	}
	return r, nil
}

