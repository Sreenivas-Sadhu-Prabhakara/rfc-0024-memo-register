package main

import (
	"fmt"
	"html/template"
	"strings"
)

const modulus uint64 = 1 << 24
const maxAdvance uint64 = 1_000_000_000_000

type Sample struct {
	Name            string `json:"name"`
	Start           uint64 `json:"start"`
	End             uint64 `json:"end"`
	TickUS          uint64 `json:"tick_us"`
	MaxAdvanceTicks uint64 `json:"max_advance_ticks"`
}
type Scenario struct {
	Samples []Sample `json:"samples"`
}
type Result struct {
	Sample
	WrapPeriodUS   uint64  `json:"wrap_period_us"`
	ResidueTicks   uint64  `json:"residue_ticks"`
	CandidateCount uint64  `json:"candidate_count"`
	Status         string  `json:"status"`
	MinGridUS      *uint64 `json:"min_grid_us,omitempty"`
	MaxGridUS      *uint64 `json:"max_grid_us,omitempty"`
}
type Report struct {
	Results []Result `json:"results"`
}

// plan solves end = (start + advances) mod 2^24 under a supplied bound.
// Grid durations describe counter advances, not exact physical elapsed time.
func plan(s Scenario) (Report, error) {
	r := Report{}
	if len(s.Samples) == 0 || len(s.Samples) > 100 {
		return r, fmt.Errorf("expected 1–100 samples")
	}
	seen := map[string]bool{}
	for _, v := range s.Samples {
		if strings.TrimSpace(v.Name) == "" || len(v.Name) > 100 || seen[v.Name] {
			return Report{}, fmt.Errorf("names must be nonblank, unique and at most 100 bytes")
		}
		seen[v.Name] = true
		if v.Start >= modulus || v.End >= modulus {
			return Report{}, fmt.Errorf("%s: readings must fit 24 bits", v.Name)
		}
		if v.TickUS != 100 && v.TickUS != 1000 {
			return Report{}, fmt.Errorf("%s: tick_us must be 100 or 1000", v.Name)
		}
		if v.MaxAdvanceTicks > maxAdvance {
			return Report{}, fmt.Errorf("%s: bound exceeds 10^12 advances", v.Name)
		}
		delta := (v.End + modulus - v.Start) % modulus
		row := Result{Sample: v, WrapPeriodUS: modulus * v.TickUS, ResidueTicks: delta, Status: "inconsistent"}
		if delta <= v.MaxAdvanceTicks {
			row.CandidateCount = (v.MaxAdvanceTicks-delta)/modulus + 1
			low := delta * v.TickUS
			high := (delta + (row.CandidateCount-1)*modulus) * v.TickUS
			row.MinGridUS = &low
			row.MaxGridUS = &high
			row.Status = "unique tick count"
			if row.CandidateCount > 1 {
				row.Status = "ambiguous"
			}
		}
		r.Results = append(r.Results, row)
	}
	return r, nil
}

